"""Shelf/box registry + the task manager's belief of where each box is (Day 19).

Pure Python (only PyYAML) so it can be unit tested without ROS. Reads
warehouse_bringup/config/registry.yaml (generated by sim/registry_gen.py).
Box occupancy starts from the registry's `boxes` section and is updated by the
task manager after each successful MoveBox (Day 23 replaces this belief with
the sim's ground-truth /boxes topic).
"""
import copy

import yaml


class TaskError(Exception):
    """A MoveBox goal that cannot be executed; str() is the failure reason."""


class Registry:
    def __init__(self, data):
        self.data = data
        self.frame = data.get("frame", "map")
        self.shelves = data["shelves"]
        g = data.get("gripper", {})
        self.lift_clearance = float(g.get("lift_clearance", 0.03))
        # box id -> (shelf, slot)
        self.boxes = {b: (v["shelf"], int(v["slot"])) for b, v in data["boxes"].items()}

    @classmethod
    def load(cls, path):
        with open(path) as f:
            return cls(yaml.safe_load(f))

    def copy(self):
        r = Registry(copy.deepcopy(self.data))
        r.boxes = dict(self.boxes)
        return r

    # --- queries -------------------------------------------------------------
    def slot(self, shelf, index):
        for s in self.shelves[shelf]["slots"]:
            if int(s["index"]) == index:
                return s
        raise TaskError(f"unknown slot {index} on {shelf}")

    def occupant(self, shelf, index):
        for b, where in self.boxes.items():
            if where == (shelf, index):
                return b
        return None

    def free_slots(self, shelf):
        return [int(s["index"]) for s in self.shelves[shelf]["slots"]
                if self.occupant(shelf, int(s["index"])) is None]

    def plan(self, box_id, target_shelf, target_slot=-1):
        """Validate a MoveBox goal. Returns a dict with source/target shelf,
        slot and the slot dicts (centre, approach, dock); raises TaskError."""
        if box_id not in self.boxes:
            raise TaskError(f"unknown box '{box_id}'")
        if target_shelf not in self.shelves:
            raise TaskError(f"unknown shelf '{target_shelf}'")
        src_shelf, src_slot = self.boxes[box_id]
        if target_slot < 0:
            free = self.free_slots(target_shelf)
            if not free:
                raise TaskError(f"no free slot on {target_shelf}")
            target_slot = free[0]
        dst = self.slot(target_shelf, target_slot)   # raises on bad index
        if (target_shelf, target_slot) == (src_shelf, src_slot):
            raise TaskError(f"{box_id} is already at {target_shelf} slot {target_slot}")
        occ = self.occupant(target_shelf, target_slot)
        if occ is not None:
            raise TaskError(f"slot occupied: {target_shelf} slot {target_slot} holds {occ}")
        return {
            "box_id": box_id,
            "src_shelf": src_shelf, "src_slot": src_slot, "src": self.slot(src_shelf, src_slot),
            "dst_shelf": target_shelf, "dst_slot": target_slot, "dst": dst,
        }

    # --- updates -------------------------------------------------------------
    def move(self, box_id, shelf, slot):
        self.boxes[box_id] = (shelf, int(slot))
