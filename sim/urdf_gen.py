"""Generate the robot URDF from robot_params (pure Python, Day 8).

  python3 sim/urdf_gen.py            # rewrite ros_ws/src/warehouse_bringup/urdf/warehouse_bot.urdf
  python3 sim/urdf_gen.py --check    # exit 1 if the checked-in URDF is stale

Frames match the sim (sim/robot.py, sim/ros_graphs.py):
  base_link       chassis centre (what /odom and TF odom->base_link track)
  base_footprint  on the floor below base_link (child of base_link, because the
                  sim already owns odom->base_link)
  left/right_wheel_link  continuous joints about +y (driven by /joint_states)
  lift_link       prismatic along +z, 0..LIFT_TRAVEL[1]
  laser           fixed at LASER_POS (the /scan frame_id)
Collision shapes mirror the sim (wheel colliders are spheres there; the URDF
uses cylinders, it is only for RViz/TF and the Nav2 footprint).
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import robot_params as P  # noqa: E402

URDF_PATH = os.path.join(HERE, "..", "ros_ws", "src", "warehouse_bringup", "urdf", "warehouse_bot.urdf")


def _f(*v):
    return " ".join(f"{x:.4f}".rstrip("0").rstrip(".") if x != 0 else "0" for x in v)


def _box_inertia(m, sx, sy, sz):
    return m * (sy * sy + sz * sz) / 12, m * (sx * sx + sz * sz) / 12, m * (sx * sx + sy * sy) / 12


def _link(name, geom, mass, inertia, rgba=None, origin=(0, 0, 0), rpy=(0, 0, 0)):
    mat = f'<material name="{name}_mat"><color rgba="{_f(*rgba)}"/></material>' if rgba else ""
    o = f'<origin xyz="{_f(*origin)}" rpy="{_f(*rpy)}"/>'
    ixx, iyy, izz = inertia
    return f"""  <link name="{name}">
    <visual>{o}<geometry>{geom}</geometry>{mat}</visual>
    <collision>{o}<geometry>{geom}</geometry></collision>
    <inertial><mass value="{_f(mass)}"/><inertia ixx="{ixx:.6f}" ixy="0" ixz="0" iyy="{iyy:.6f}" iyz="0" izz="{izz:.6f}"/></inertial>
  </link>
"""


def _joint(name, jtype, parent, child, xyz, axis=None, limit=None):
    a = f'\n    <axis xyz="{_f(*axis)}"/>' if axis else ""
    lim = ""
    if limit:
        lim = f'\n    <limit lower="{_f(limit[0])}" upper="{_f(limit[1])}" effort="{_f(limit[2])}" velocity="{_f(limit[3])}"/>'  # noqa: E501
    return f"""  <joint name="{name}" type="{jtype}">
    <parent link="{parent}"/><child link="{child}"/>
    <origin xyz="{_f(*xyz)}" rpy="0 0 0"/>{a}{lim}
  </joint>
"""


def generate():
    cz = P.chassis_centre_z()
    cs = P.CHASSIS_SIZE
    out = ['<?xml version="1.0"?>\n',
           "<!-- GENERATED by sim/urdf_gen.py from sim/robot_params.py - do not edit by hand -->\n",
           '<robot name="warehouse_bot">\n']
    out.append(_link("base_link", f'<box size="{_f(*cs)}"/>', P.CHASSIS_MASS,
                     _box_inertia(P.CHASSIS_MASS, *cs), (0.9, 0.55, 0.1, 1)))
    out.append('  <link name="base_footprint"/>\n')
    out.append(_joint("base_footprint_joint", "fixed", "base_link", "base_footprint", (0, 0, -cz)))
    r, w, m = P.WHEEL_RADIUS, P.WHEEL_WIDTH, P.WHEEL_MASS
    wi = (m * (3 * r * r + w * w) / 12, m * r * r / 2, m * (3 * r * r + w * w) / 12)
    for side, sy in (("left", 1.0), ("right", -1.0)):
        out.append(_link(f"{side}_wheel_link", f'<cylinder radius="{_f(r)}" length="{_f(w)}"/>', m, wi,
                         (0.1, 0.1, 0.1, 1), rpy=(1.5708, 0, 0)))
        out.append(_joint(f"{side}_wheel_joint", "continuous", "base_link", f"{side}_wheel_link",
                          (0, sy * P.WHEEL_SEPARATION / 2, P.WHEEL_RADIUS - cz), axis=(0, 1, 0)))
    for name, sx in (("caster_front", P.CASTER_X), ("caster_back", -P.CASTER_X)):
        cr = P.CASTER_RADIUS
        out.append(_link(f"{name}_link", f'<sphere radius="{_f(cr)}"/>', 0.05, (1e-5, 1e-5, 1e-5),
                         (0.6, 0.6, 0.65, 1)))
        out.append(_joint(f"{name}_joint", "fixed", "base_link", f"{name}_link", (sx, 0, cr - cz)))
    ls = P.LIFT_SIZE
    lz = P.chassis_top_z() + ls[2] / 2 - cz
    out.append(_link("lift_link", f'<box size="{_f(*ls)}"/>', P.LIFT_MASS, _box_inertia(P.LIFT_MASS, *ls),
                     (0.6, 0.6, 0.65, 1)))
    out.append(_joint("lift_joint", "prismatic", "base_link", "lift_link", (0, 0, lz), axis=(0, 0, 1),
                      limit=(P.LIFT_TRAVEL[0], P.LIFT_TRAVEL[1], 500.0, 0.2)))
    out.append(_link("laser", '<cylinder radius="0.03" length="0.04"/>', 0.1, (1e-4, 1e-4, 1e-4),
                     (0.1, 0.1, 0.1, 1)))
    out.append(_joint("laser_joint", "fixed", "base_link", "laser", P.LASER_POS))
    out.append("</robot>\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=URDF_PATH)
    a = ap.parse_args()
    text = generate()
    if a.check:
        cur = open(a.out).read() if os.path.exists(a.out) else ""
        if cur != text:
            print(f"STALE: {a.out} (run python3 sim/urdf_gen.py)")
            return 1
        print("URDF up to date")
        return 0
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(a.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
