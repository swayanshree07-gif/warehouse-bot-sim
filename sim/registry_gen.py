"""Shelf/box registry (Day 15): generated from warehouse_layout + robot_params.

  python3 sim/registry_gen.py           # rewrite ros_ws/src/warehouse_bringup/config/registry.yaml
  python3 sim/registry_gen.py --check   # exit 1 if the checked-in registry is stale

The registry is what the task manager (Days 19+) reads: every shelf, its slots
and, per slot, two robot poses in the **map** frame (map = world - spawn, the
spawn pose is world (-2, 0, yaw 0), see README):
  approach  Nav2 goal, APPROACH_STANDOFF from the slot centre, facing the rack
  dock      final pose for the gripper, DOCK_STANDOFF (= GRIP_REACH) from the
            slot centre; reached with a precise docking controller (Day 20)
Poses are [x, y, yaw_deg]. Every rack is served from the side that faces the
central aisle (y = 0), which is 1.8+ m wide. `boxes` gives the initial box
placement (box id -> shelf, slot); 12 slots, 10 boxes, so shelf_D slots 1 and 2
start empty.
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import robot_params as P  # noqa: E402
import warehouse_layout as L  # noqa: E402

import yaml  # noqa: E402

REGISTRY_PATH = os.path.join(HERE, "..", "ros_ws", "src", "warehouse_bringup", "config", "registry.yaml")
SPAWN_WORLD = (-2.0, 0.0, 0.0)   # x, y, yaw_deg; the map frame origin


def world_to_map(x, y):
    # spawn yaw is 0, so the map frame is a pure translation of the world frame
    return x - SPAWN_WORLD[0], y - SPAWN_WORLD[1]


def _r(v, n=3):
    return round(float(v), n) + 0.0   # + 0.0 turns -0.0 into 0.0


def access_side(shelf):
    """+1 if the robot stands on the +y side of the rack, -1 for the -y side."""
    return -1 if shelf.y > 0 else 1


def slot_pose(shelf, slot_xy, standoff):
    """Robot pose [x, y, yaw_deg] (map) `standoff` from the slot centre, facing it."""
    side = access_side(shelf)
    wx, wy = slot_xy[0], slot_xy[1] + side * standoff
    mx, my = world_to_map(wx, wy)
    yaw = math.degrees(math.atan2(-side, 0.0))   # face the rack
    return [_r(mx), _r(my), _r(yaw, 1)]


def build():
    sx, sy, sz = L.SHELF_SIZE
    shelves = {}
    for s in L.SHELVES:
        cx, cy = world_to_map(s.x, s.y)
        slots = []
        for i, (x, y, ztop) in enumerate(s.slots):
            mx, my = world_to_map(x, y)
            slots.append({
                "index": i,
                "center": [_r(mx), _r(my), _r(ztop + L.BOX_SIZE / 2)],
                "approach": slot_pose(s, (x, y), P.APPROACH_STANDOFF),
                "dock": slot_pose(s, (x, y), P.DOCK_STANDOFF),
            })
        shelves[s.name] = {
            "center": [_r(cx), _r(cy)],
            "yaw_deg": _r(s.yaw_deg, 1),
            "size": [_r(sx), _r(sy), _r(sz)],
            "access_side": "+y" if access_side(s) > 0 else "-y",
            "slots": slots,
        }
    boxes = {b.name: {"shelf": b.shelf, "slot": b.slot} for b in L.BOXES}
    return {
        "frame": "map",
        "map_origin_in_world": [_r(v, 1) for v in SPAWN_WORLD],
        "box_size": _r(L.BOX_SIZE),
        "gripper": {
            "reach": _r(P.GRIP_REACH),
            "tolerance": _r(P.GRIP_TOL),
            "lift_clearance": _r(P.LIFT_CLEARANCE),
        },
        "shelves": shelves,
        "boxes": boxes,
    }


HEADER = ("# GENERATED by sim/registry_gen.py from sim/warehouse_layout.py and\n"
          "# sim/robot_params.py - do not edit by hand. Poses: [x, y, yaw_deg] in the map frame.\n")


def generate():
    return HEADER + yaml.safe_dump(build(), sort_keys=False, default_flow_style=None, width=100)


def load(path=REGISTRY_PATH):
    with open(path) as f:
        return yaml.safe_load(f)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=REGISTRY_PATH)
    a = ap.parse_args()
    text = generate()
    if a.check:
        cur = open(a.out).read() if os.path.exists(a.out) else ""
        if cur != text:
            print(f"STALE: {a.out} (run python3 sim/registry_gen.py)")
            return 1
        print("registry up to date")
        return 0
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(a.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
